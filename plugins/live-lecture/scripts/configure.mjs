import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { BridgeClient } from './server.mjs';
const [flag, file, ...extra] = process.argv.slice(2);
if (flag !== '--import' || !file || extra.length) throw Error('Usage: node scripts/configure.mjs --import path/to/aha-lecture-connection.json');
const config = JSON.parse(await readFile(file, 'utf8'));
const client = new BridgeClient(config);
const context = await client.request('context');
if (context.id !== config.lectureId) throw Error('Connection file and lecture do not match.');
await mkdir(new URL('../.local/', import.meta.url), { recursive: true });
await writeFile(new URL('../.local/connection.json', import.meta.url), JSON.stringify(config), { mode: 0o600 });
console.log(`Connected to ${context.title}. Expires ${context.expiresAt}. Connection token was not printed.`);
